'use client';
import type { Metadata } from 'next';
import { Inter } from 'next/font/google';
import './globals.css';
import { Footer, Header, Sole } from '@irachus/ui';
import { LOCALISATION, BANNER, MENU_LIST,  socialNetowrk, internalLinkList } from '../common/constant';
import '../common/i18n';
import { useTranslation } from 'react-i18next';
import {  pageContainsInit} from '@irachus/jscommon';
import useMenuList from '../hooks/useMenuList';
import useFooterContain from '../hooks/useFooterContains';
import useEnhancedLink from '../hooks/useEnhancedLink';
import { useEffect, useState } from 'react';
import useLocalisation from '../hooks/useLocalisation';
const inter = Inter({ subsets: ['latin'] });

// export const metadata: Metadata = {
